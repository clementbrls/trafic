const dicts: Record<Lang, Dict> = { fr, en };
let current: Lang = 'fr';

export type StrKey = keyof Dict;

export function setLang(l: Lang): void {
  current = l;
  document.documentElement.lang = l;
}

export function getLang(): Lang {
  return current;
}

export function detectLang(): Lang {
  const n = (navigator.language || 'fr').toLowerCase();
  return n.startsWith('fr') ? 'fr' : 'en';
}

export function t(key: StrKey, params?: Record<string, string | number>): string {
  let s: string = dicts[current][key] ?? dicts.fr[key] ?? key;
  if (params) for (const k of Object.keys(params)) s = s.replace(`{${k}}`, String(params[k]));
  return s;
}
